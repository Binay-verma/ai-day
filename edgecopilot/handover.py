"""Shift handover report and cross-camera incident correlation.

* :func:`correlate` groups alerts that are probably one real-world incident: same zone,
  overlapping in time (within ``window_s`` of the previous alert of the group), across
  cameras, hazards and sensors - e.g. a smoke alert on one camera, a rapid-exit crowd
  alert on the next camera and an MQ-2 spike in the same zone within a minute. The
  operator sees one incident with its evidence trail instead of three pages.
* :func:`build_handover` summarises a shift for the next operator: open incidents first,
  what happened, what was dismissed, what is degraded (camera faults, paused cameras,
  failing self-tests, calibration drift). :func:`render_handover` makes a printable page.

Everything here is computed from the alert store and the live service state; nothing
is generated by a language model, so every line can be traced to records.
"""
from __future__ import annotations

import html
import time
from collections import Counter
from typing import Any, Dict, List, Optional

from .service import utc_iso


def correlate(alerts: List[Dict[str, Any]], window_s: float = 120.0) -> List[Dict[str, Any]]:
    """Group alerts into incidents by zone and time proximity (trouble alerts excluded)."""
    rows = sorted((a for a in alerts if a.get("hazard") not in ("camera_fault", "self_test")),
                  key=lambda a: a.get("wall_time") or 0.0)
    open_groups: Dict[str, Dict[str, Any]] = {}
    out: List[Dict[str, Any]] = []
    for a in rows:
        z = a.get("zone") or "?"
        t = a.get("wall_time") or 0.0
        g = open_groups.get(z)
        if g is None or t - g["end"] > window_s:
            g = {"zone": z, "start": t, "end": t, "alerts": [], "hazards": Counter(), "cameras": set()}
            open_groups[z] = g
            out.append(g)
        g["end"] = t
        g["alerts"].append(a)
        g["hazards"][a.get("hazard")] += 1
        g["cameras"].add(a.get("camera_id"))
    res = []
    for g in out:
        al = g["alerts"]
        sev_rank = {"CRITICAL": 3, "HIGH": 2, "MEDIUM": 1, "LOW": 0}
        top = max(al, key=lambda a: (sev_rank.get(a.get("severity", ""), 0), a.get("peak_prob") or a.get("prob") or 0))
        res.append({"zone": g["zone"], "start_utc": utc_iso(g["start"]), "end_utc": utc_iso(g["end"]),
                    "duration_s": round(g["end"] - g["start"], 1), "n_alerts": len(al),
                    "hazards": dict(g["hazards"]), "cameras": sorted(c for c in g["cameras"] if c),
                    "multi_signal": len(g["hazards"]) > 1 or len(g["cameras"]) > 1,
                    "severity": top.get("severity"), "headline": (top.get("explanation") or {}).get("headline", ""),
                    "open": any(a.get("status") == "open" for a in al), "alert_ids": [a["id"] for a in al]})
    return res


def build_handover(service, hours: float = 12.0, now: Optional[float] = None) -> Dict[str, Any]:
    now = now or time.time()
    since = now - hours * 3600
    alerts = service.store.list_alerts(500, since=since)
    hazards = [a for a in alerts if a.get("hazard") not in ("camera_fault", "self_test")]
    faults = [a for a in alerts if a.get("hazard") == "camera_fault"]
    by_status: Dict[str, Counter] = {}
    for a in hazards:
        by_status.setdefault(a["hazard"], Counter())[a.get("status", "open")] += 1
    incidents = correlate(hazards)
    cams = []
    for cid, w in service.cameras.items():
        st = w.status()
        cop = getattr(w, "copilot", None)
        thr = {hz: round(m.threshold, 3) for hz, m in cop.models.items()} if cop else {}
        cams.append({"id": cid, "zone": st["zone"], "state": st["health"]["state"], "paused": st.get("paused", False),
                     "paused_by": st.get("paused_by", ""), "alert_lines": thr})
    st = service.last_self_test or {}
    return {
        "generated_utc": utc_iso(now), "period_hours": hours, "from_utc": utc_iso(since),
        "open_incidents": [i for i in incidents if i["open"]],
        "incidents": incidents,
        "counts": {hz: dict(c) for hz, c in by_status.items()},
        "long_lie_escalations": sum(1 for a in hazards if a.get("severity") == "CRITICAL" and a.get("hazard") == "fall"),
        "dismissed": [{"id": a["id"], "hazard": a["hazard"], "zone": a.get("zone"), "time_utc": utc_iso(a.get("wall_time")),
                       "by": a.get("operator") or "", "note": a.get("operator_note") or ""}
                      for a in hazards if a.get("status") == "dismissed"],
        "camera_faults": [{"camera": a.get("camera_id"), "kind": a.get("subject"), "time_utc": utc_iso(a.get("wall_time")),
                           "status": a.get("status")} for a in faults],
        "cameras": cams,
        "self_test": {"ok": st.get("ok"), "time_utc": st.get("time_utc")},
    }


def render_handover(d: Dict[str, Any], user: str) -> str:
    e = lambda x: html.escape(str(x if x is not None else ""))  # noqa: E731

    def table(rows, cols):
        if not rows:
            return "<p class=muted>None.</p>"
        head = "".join(f"<th>{e(c)}</th>" for c in cols)
        body = "".join("<tr>" + "".join(f"<td>{e(r.get(c, ''))}</td>" for c in cols) + "</tr>" for r in rows)
        return f"<table><tr>{head}</tr>{body}</table>"
    inc_rows = [{"zone": i["zone"], "start (UTC)": i["start_utc"], "severity": i["severity"], "what": i["headline"],
                 "signals": ", ".join(f"{k}x{v}" for k, v in i["hazards"].items()) + (" (multi-signal)" if i["multi_signal"] else ""),
                 "cameras": ", ".join(i["cameras"])} for i in d["incidents"]]
    open_rows = [r for r, i in zip(inc_rows, d["incidents"]) if i["open"]]
    cnt_rows = [{"hazard": hz, **c} for hz, c in d["counts"].items()]
    cam_rows = [{"camera": c["id"], "zone": c["zone"], "state": c["state"] + (" (PAUSED by " + c["paused_by"] + ")" if c["paused"] else ""),
                 "alert lines": ", ".join(f"{k} {v:.0%}" for k, v in c["alert_lines"].items())} for c in d["cameras"]]
    st = d["self_test"]
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>Shift handover</title>
<style>body{{font:14px system-ui,sans-serif;margin:24px;color:#111}}h1{{font-size:20px}}h2{{font-size:16px;margin-top:22px}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ccc;padding:4px 6px;text-align:left;vertical-align:top}}
th{{background:#f2f2f2}}.muted{{color:#666}}.warn{{color:#a40}}</style></head><body>
<h1>Shift handover - edge copilot</h1>
<p>Period: last {e(d['period_hours'])} h (from {e(d['from_utc'])} to {e(d['generated_utc'])}). Prepared for {e(user)}.
Every line is computed from the incident store and the audit trail.</p>
<h2>1. Open incidents (need follow-up)</h2>{table(open_rows, ['zone', 'start (UTC)', 'severity', 'what', 'signals', 'cameras'])}
<h2>2. All incidents this shift (alerts grouped by zone and time)</h2>{table(inc_rows, ['zone', 'start (UTC)', 'severity', 'what', 'signals', 'cameras'])}
<h2>3. Alert outcomes by hazard</h2>{table(cnt_rows, ['hazard', 'open', 'confirmed', 'dismissed', 'resolved'])}
<p>Long-lie escalations (person still down after a fall): {e(d['long_lie_escalations'])}</p>
<h2>4. Dismissed as false alarms</h2>{table(d['dismissed'], ['time_utc', 'hazard', 'zone', 'by', 'note'])}
<h2>5. System health</h2>{table(cam_rows, ['camera', 'zone', 'state', 'alert lines'])}
<p class="{'' if st.get('ok') else 'warn'}">Last self-test: {e('passed' if st.get('ok') else ('FAILED' if st.get('ok') is False else 'not run yet'))}
{e(st.get('time_utc') or '')}</p>
<h3>Camera trouble signals</h3>{table(d['camera_faults'], ['time_utc', 'camera', 'kind', 'status'])}
<p class=muted>Decision support only: supplements, and never replaces, the certified fire alarm system and emergency services (112 / 108 / 101).</p>
</body></html>"""
